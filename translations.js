function i18n(page) {
    const urlParams = new URLSearchParams(window.location.search);
    let lang = urlParams.get('lang') || localStorage.getItem('preferredLang') || navigator.language.split('-')[0];
    
    if (!translations[lang]) lang = 'en';
    

    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            let content = translations[lang][key];
            if (el.tagName === 'A' && key === 'policyLink') {
                el.innerText = content;
            } else {
                // Simple markdown-to-html for bold and italics
                content = content.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>');
                content = content.replace(/\*(.*?)\*/g, '<em>$1</em>');
                el.innerHTML = content;
            }
        }
    });

    document.documentElement.lang = lang;
    document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';
    
    if (page === 'privacy') {
        document.title = (translations[lang]?.privacyTitle || "Privacy Policy") + " - Color Cage";
    } else {
        document.title = "Color Cage - " + translations[lang]?.langName + (lang === 'ko' ? ' 지원' : ' Support');
    }

    localStorage.setItem('preferredLang', lang);
}

function changeLang(lang) {
    const url = new URL(window.location);
    url.searchParams.set('lang', lang);
    window.location.href = url.toString(); // Using href for clean reload with direction change
}
